export type MoveMatchKind = "exact" | "kana" | "alias" | "none";

/**
 * 技名をチャンピオンズの表記にする（あいまい一致はしない。確実な場合だけ）。
 *  - exact: 表のとおり
 *  - kana : かなの種類・空白・「・」だけが違う（例: 「ムーンフォース」「むーんふぉーす」）
 *  - alias: 漢字表記（対応表にあるもの）。先頭に余計なかなが付いた形（「ふ不意打ち」）も直す
 *  - none : どれにも当てはまらない（そのまま返す）
 */
export function canonicalMove(raw: string): { name: string; kind: MoveMatchKind } {
  const s = raw.normalize("NFKC").trim();
  if (!s) return { name: raw, kind: "none" };
  // ゲームの表記は「１０まんボルト」（数字が全角）。表の表記のまま通す
  if (raw.trim() in MOVE_TYPES) return { name: raw.trim(), kind: "exact" };
  if (s in MOVE_TYPES) return { name: s, kind: "exact" };

  const folded = FOLDED.get(foldKana(s));
  if (folded) return { name: folded, kind: "kana" };

  // 漢字表記。AIが先頭のかなを重ねた形（例: 「ふ不意打ち」＝「ふ」+「不意打ち」）も拾うため、先頭を最大2文字まで外して探す
  if (/[一-鿿]/.test(s)) {
    for (let i = 0; i <= 2 && i < s.length; i++) {
      const hit = MOVE_ALIASES[s.slice(i)];
      if (hit && hit in MOVE_TYPES) return { name: hit, kind: "alias" };
    }
  }
  return { name: raw, kind: "none" };
}
