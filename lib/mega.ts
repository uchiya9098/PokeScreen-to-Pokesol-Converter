export interface MegaResult {
  /** メガシンカ後の名前（例: メガリザードンX） */
  name: string;
  /** メガシンカ後の特性（例: かたいツメ） */
  megaAbility: string;
}

/**
 * 持ち物がメガストーン（「○○ナイト」「○○ナイトX/Y/Z」）で、対応するメガシンカが表にあれば、
 * メガシンカ後の名前と特性を返す。該当しなければ null。
 * 別のポケモンのメガストーンを誤って変換しないよう、ストーン名と種族名の先頭2文字が合うことを確認する。
 */
export function megaFor(name: string, item: string): MegaResult | null {
  const stone = item.trim().match(/^(.+?)ナイト([XYZ])?$/);
  if (!stone) return null;
  const species = name.trim();
  if (species.startsWith("メガ")) return null;
  if (species.slice(0, 2) !== stone[1].slice(0, 2)) return null;
  const megaName = `メガ${species}${stone[2] ?? ""}`;
  const megaAbility = MEGA_ABILITIES[megaName];
  return megaAbility ? { name: megaName, megaAbility } : null;
}
